#!/usr/bin/env python3
"""Task 1.1 — Verify actual dataset contents BEFORE anything else.

Walks every dataset folder under ``data/raw/`` and writes
``data/raw/DATASET_AUDIT.md`` with one row per dataset:

    name | image_count | has_masks(Y/N) | has_lookalike_class(Y/N)
    has_any_geo_or_time_metadata(Y/N) | format | notes

Usage::

    python scripts/audit_datasets.py                  # audit data/raw/*
    python scripts/audit_datasets.py path/to/raw
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import numpy as np

from proced.config import MASK_NAME_TOKENS, RASTER_EXTENSIONS
from proced.raster_io import open_any

LOOKALIKE_HINTS = ("lookalike", "look-alike", "look_alike", "ls_", "_ls")
TIME_KEYS = ("TIFFTAG_DATETIME", "TIFFTAG_TIMESTAMP", "TIME", "ACQUISITION_TIME",
             "TIFFTAG_SOFTWARE")


def _looks_like_mask(p: Path) -> bool:
    toks = [t for t in p.stem.lower().replace("-", "_").split("_") if t]
    return any(t in MASK_NAME_TOKENS for t in toks)


def audit_one(folder: Path) -> dict:
    rasters = [p for p in sorted(folder.rglob("*"))
               if p.is_file() and p.suffix.lower() in RASTER_EXTENSIONS]
    images = [p for p in rasters if not _looks_like_mask(p)]
    masks = [p for p in rasters if _looks_like_mask(p)]
    csvs = list(folder.glob("*.csv")) + list(folder.glob("*.json"))

    has_masks = len(masks) > 0
    fmt = sorted({p.suffix.lower().lstrip(".") for p in rasters}) or ["none"]

    has_geo_time = False
    dims = ""
    notes = []
    mask_values = set()

    probe = images[0] if images else (masks[0] if masks else None)
    if probe is not None:
        try:
            with open_any(probe) as ds:
                dims = f"{ds.width}x{ds.height}x{ds.count} {ds.dtypes[0]}"
                if ds.crs is not None and not ds.transform.is_identity:
                    has_geo_time = True
                tags = ds.tags()
                if any(tags.get(k) for k in TIME_KEYS):
                    has_geo_time = True
        except Exception as exc:
            notes.append(f"probe failed: {exc}")

    # Look-alike detection: folder/filename hints OR mask value > 1
    name_l = str(folder).lower()
    has_lookalike = any(h in name_l for h in LOOKALIKE_HINTS)
    for mp in masks[:5]:
        try:
            with open_any(mp) as ds:
                arr = ds.read(1)
            uniq = np.unique(arr)
            mask_values.update(int(v) for v in uniq[:10])
            if len([v for v in uniq if v > 1]) > 0:
                has_lookalike = True
        except Exception:
            pass
    if mask_values:
        notes.append(f"mask values seen: {sorted(mask_values)}")
    if csvs:
        notes.append(f"metadata files: {[c.name for c in csvs[:3]]}")
        has_geo_time = True  # metadata csv/json present → treat as possible geo/time
    if not images:
        notes.append("no non-mask images found")

    return {
        "name": folder.name,
        "image_count": len(images),
        "mask_count": len(masks),
        "has_masks": "Y" if has_masks else "N",
        "has_lookalike": "Y" if has_lookalike else "N",
        "has_geo_time": "Y" if has_geo_time else "N",
        "format": "+".join(fmt),
        "dims": dims,
        "notes": "; ".join(notes),
    }


def write_audit(rows, out_path: Path) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# DATASET_AUDIT — Task 1.1",
        "",
        "Generated by `scripts/audit_datasets.py`. **Do not proceed to Task 1.2 "
        "until this is shared with the Model Training team.**",
        "",
        "| name | image_count | has_masks(Y/N) | has_lookalike_class(Y/N) "
        "| has_any_geo_or_time_metadata(Y/N) | format | notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['name']} | {r['image_count']} | {r['has_masks']} "
            f"| {r['has_lookalike']} | {r['has_geo_time']} | {r['format']} "
            f"| {r['dims']}; {r['notes']} |"
        )
    lines.append("")
    out_path.write_text("\n".join(lines), encoding="utf-8")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("root", nargs="?", default=str(ROOT / "data" / "raw"))
    ap.add_argument("--out", default=str(ROOT / "data" / "raw" / "DATASET_AUDIT.md"))
    args = ap.parse_args(argv)

    root = Path(args.root)
    if not root.is_dir():
        print(f"ERROR: {root} is not a directory", file=sys.stderr)
        return 1

    # Each immediate subdirectory = one dataset; loose files audited as one row
    dataset_dirs = sorted([d for d in root.iterdir() if d.is_dir() and not d.name.startswith(".")])
    rows = [audit_one(d) for d in dataset_dirs]
    if not rows:
        print(f"No dataset folders under {root} — download datasets first (Task 1.1).")
        write_audit([], Path(args.out))
        return 0

    write_audit(rows, Path(args.out))
    print(f"Audited {len(rows)} dataset(s) → {args.out}")
    for r in rows:
        print(f"  {r['name']}: {r['image_count']} images, masks={r['has_masks']}, "
              f"lookalike={r['has_lookalike']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
